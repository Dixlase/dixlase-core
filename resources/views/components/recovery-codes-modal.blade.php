                    <span class="ml-3 text-sm text-red-800 dark:text-red-200 font-semibold">
                        <i class="fas fa-exclamation-circle mr-1"></i>
                        {{ __('two-factor.recovery_codes.confirm_saved') }}
                    </span>
                </label>
            </div>
