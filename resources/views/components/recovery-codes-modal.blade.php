@props([
    'modalId' => 'recoveryCodesModal',
    'title' => null,
    'codes' => [],
    'isAutoGenerated' => false,
    'autoOpen' => false,
    'isDynamic' => false, // JavaScriptで動的に表示する場合
    'error' => null, // エラーメッセージ（エラー表示モード）
    'clearSessionRoute' => null, // セッションクリア用ルート（自動生成時のみ）
])

<x-modal :id="$modalId" :title="$error ? __('common.error') : ($title ?? __('two-factor.recovery_codes.title'))" :icon_type="$error ? 'danger' : 'warning'">
    <div class="space-y-4">
        @if($error)
            {{-- エラー表示モード --}}
            <div class="bg-red-50 dark:bg-red-900/20 border border-red-200 dark:border-red-800 rounded-lg p-4">
                <p class="text-sm text-red-800 dark:text-red-200">
                    <i class="fas fa-exclamation-circle mr-2"></i>
                    {{ $error }}
                </p>
            </div>
        @else
            {{-- 回復コード表示モード --}}
            @if($isAutoGenerated)
            <div class="bg-blue-50 dark:bg-blue-900/20 border border-blue-200 dark:border-blue-800 rounded-lg p-4">
                <p class="text-sm text-blue-800 dark:text-blue-200">
                    <i class="fas fa-info-circle mr-2"></i>
                    {{ __('two-factor.recovery_codes.auto_generated_message') }}
                </p>
            </div>
            @endif
            
            <div class="bg-yellow-50 dark:bg-yellow-900/20 border border-yellow-200 dark:border-yellow-800 rounded-lg p-4">
                <p class="text-sm text-yellow-800 dark:text-yellow-200">
                    <i class="fas fa-exclamation-triangle mr-2"></i>
                    {{ __('two-factor.recovery_codes.warning') }}
                </p>
            </div>
            
            <div class="bg-gray-50 dark:bg-gray-800 rounded-lg p-4">
                <div id="{{ $modalId }}-codes-list" class="space-y-2 font-mono text-sm">
                    @if(!$isDynamic)
                        @foreach($codes as $code)
                            <div class="p-2 bg-white dark:bg-gray-700 rounded border border-gray-200 dark:border-gray-600 text-center">
                                {{ implode('-', str_split($code, 5)) }}
                            </div>
                        @endforeach
                    @else
                        <!-- JavaScriptで動的に追加 -->
                    @endif
                </div>
            </div>
            
