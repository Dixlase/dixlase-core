            class="px-4 py-2 bg-gray-600 hover:bg-gray-700 text-white rounded-md shadow-sm focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-gray-500 @if(!$error) opacity-50 cursor-not-allowed @endif">
            {{ __('common.close') }}
        </button>
    </x-slot>
