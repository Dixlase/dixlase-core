declare(strict_types=1);

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

/**
 * Per-site theme activation record.
 *
 * Each site has at most one active theme; the application layer
 * enforces that invariant by deactivating the previous active theme
 * when a new one is enabled.
 */
class SiteThemeActivation extends Model
{
    use HasFactory;

    protected $table = 'site_theme_activations';

    protected $fillable = [
        'site_id',
        'theme_id',
        'is_active',
        'activated_at',
        'settings',
    ];

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'is_active' => 'boolean',
            'activated_at' => 'datetime',
            'settings' => 'array',
        ];
    }

    public function site(): BelongsTo
    {
        return $this->belongsTo(Site::class);
    }

    public function theme(): BelongsTo
    {
        return $this->belongsTo(Theme::class);
    }
}
