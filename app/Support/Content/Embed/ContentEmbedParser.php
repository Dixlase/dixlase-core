declare(strict_types=1);

namespace App\Support\Content\Embed;

use League\CommonMark\Node\Block\AbstractBlock;
use League\CommonMark\Parser\Block\BlockContinue;
use League\CommonMark\Parser\Block\BlockContinueParserInterface;
use League\CommonMark\Parser\Cursor;

/**
 * Hold one embed line; an embed never spans more than its own line
 */
class ContentEmbedParser implements BlockContinueParserInterface
{
    private ContentEmbed $embed;

    public function __construct(string $service, string $url)
    {
        $this->embed = new ContentEmbed($service, $url);
    }

    public function getBlock(): AbstractBlock
    {
        return $this->embed;
    }

    public function isContainer(): bool
    {
        return false;
    }

    public function canHaveLazyContinuationLines(): bool
    {
        return false;
    }

    public function canContain(AbstractBlock $childBlock): bool
    {
        return false;
    }

    public function tryContinue(Cursor $cursor, BlockContinueParserInterface $activeBlockParser): ?BlockContinue
    {
        return BlockContinue::none();
    }

    public function addLine(string $line): void {}

    public function closeBlock(): void {}
}
