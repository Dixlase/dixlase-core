declare(strict_types=1);

namespace App\Enums;

/**
 * Setting key scope (3-mode model).
 *
 * Each setting key falls into exactly one of these scopes, which dictates
 * where its value is stored and how SettingResolver merges it:
 *
 *   - Global       network-wide; stored in global_settings only
 *   - PerSite      site-specific; stored in site_settings only
 *   - Overridable  global default + per-site override; both tables
 */
enum SettingScope: string
{
    case Global = 'global';
    case PerSite = 'per_site';
    case Overridable = 'overridable';
}
