declare(strict_types=1);

namespace App\Exceptions\Install;

/**
 * @internal For Core use only. Do not reference from plugins/themes
 *
 * The SQLite database file cannot be created or written.
 *
 * Laravel's SQLite connector throws instead of creating a missing file,
 * so the installation stops here rather than half-way through the
 * migrations with a rewritten .env already on disk.
 */
class SqliteDatabaseUnusableException extends \RuntimeException
{
    public function __construct(public readonly string $path)
    {
        parent::__construct("The SQLite database file could not be created or written: {$path}");
    }
}
