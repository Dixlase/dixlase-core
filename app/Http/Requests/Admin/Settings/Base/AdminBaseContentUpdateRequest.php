namespace App\Http\Requests\Admin\Settings\Base;

use App\Services\FrontPageRevisionService;
use Illuminate\Foundation\Http\FormRequest;

class AdminBaseContentUpdateRequest extends FormRequest
{
    public function authorize(): bool
    {
        return true;
    }

    /**
     * @return array<string, \Illuminate\Contracts\Validation\ValidationRule|array<mixed>|string>
     */
    public function rules(): array
    {
        return [
            'revision_retention_count' => 'required|integer|min:0|max:'.FrontPageRevisionService::MAX_RETENTION,
        ];
    }
}
