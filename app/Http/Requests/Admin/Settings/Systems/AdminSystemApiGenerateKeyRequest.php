namespace App\Http\Requests\Admin\Settings\Systems;

use Illuminate\Foundation\Http\FormRequest;

class AdminSystemApiGenerateKeyRequest extends FormRequest
{
    /**
     * Determine if the user is authorized to make this request.
     */
    public function authorize(): bool
    {
        return true;
    }

    /**
     * Prepare the data for validation.
     */
    protected function prepareForValidation(): void
    {
        // Convert empty strings to null
        $data = [];

        if ($this->rate_limit === '') {
            $data['rate_limit'] = null;
        }

        if ($this->expires_at === '') {
            $data['expires_at'] = null;
        }

        if ($this->description === '') {
            $data['description'] = null;
        }

        if (! empty($data)) {
            $this->merge($data);
        }
    }

    /**
     * Get the validation rules that apply to the request.
     *
     * @return array<string, \Illuminate\Contracts\Validation\ValidationRule|array<mixed>|string>
     */
    public function rules(): array
    {
        return [
            'name' => 'required|string|max:100',
            'environment' => 'required|in:live,test',
            'scopes' => 'nullable|array',
            'scopes.*' => 'string',
            'rate_limit' => 'nullable|integer|min:0|max:10000',
            'allowed_ips' => 'nullable|string',
            'expires_at' => 'nullable|date|after:today',
            'description' => 'nullable|string|max:500',
        ];
    }
}
